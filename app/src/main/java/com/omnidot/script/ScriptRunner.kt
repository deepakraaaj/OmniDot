package com.omnidot.script

import org.mozilla.javascript.BaseFunction
import org.mozilla.javascript.Context
import org.mozilla.javascript.ContextFactory
import org.mozilla.javascript.NativeJSON
import org.mozilla.javascript.RhinoException
import org.mozilla.javascript.Scriptable
import org.mozilla.javascript.ScriptableObject
import org.mozilla.javascript.Undefined

data class ScriptResult(val ok: Boolean, val logs: List<String>, val error: String? = null)

/** Runs workflow JavaScript in a sandbox: no Java access, a time limit, and only the `omni` API. */
class ScriptRunner(private val timeoutMs: Long = 10_000) {

    private class Timeout : Error()

    private inner class SandboxFactory(private val deadline: Long) : ContextFactory() {
        override fun makeContext(): Context = super.makeContext().apply {
            optimizationLevel = -1 // Android cannot load generated bytecode; interpret instead.
            languageVersion = Context.VERSION_ES6
            instructionObserverThreshold = 5_000
            setClassShutter { false } // no Java classes are visible to scripts
        }

        override fun observeInstructionCount(cx: Context, instructionCount: Int) {
            if (System.currentTimeMillis() > deadline) throw Timeout()
        }
    }

    fun compileError(code: String): String? = SandboxFactory(Long.MAX_VALUE).call { cx ->
        try {
            cx.compileString(code, "script", 1, null)
            null
        } catch (e: RhinoException) {
            "Line ${e.lineNumber()}: ${e.details()}"
        }
    } as String?

    fun run(code: String, event: Map<String, Any?>, api: OmniApi): ScriptResult {
        val logs = mutableListOf<String>()
        val factory = SandboxFactory(System.currentTimeMillis() + timeoutMs)
        return factory.call { cx ->
            try {
                val scope = cx.initSafeStandardObjects()
                ScriptableObject.putProperty(scope, "event", toJs(cx, scope, event))
                ScriptableObject.putProperty(scope, "log", fn(scope) { args -> logs += args.joinToString(" ") { show(cx, scope, it) }; null })
                ScriptableObject.putProperty(scope, "omni", omni(cx, scope, api))
                cx.evaluateString(scope, code, "script", 1, null)
                ScriptResult(true, logs)
            } catch (e: Timeout) {
                ScriptResult(false, logs, "Script took too long (over ${timeoutMs / 1000.0} s)")
            } catch (e: RhinoException) {
                ScriptResult(false, logs, "Line ${e.lineNumber()}: ${e.details()}")
            } catch (e: Exception) {
                ScriptResult(false, logs, e.message ?: e.javaClass.simpleName)
            }
        } as ScriptResult
    }

    private fun omni(cx: Context, scope: Scriptable, api: OmniApi): Scriptable {
        fun obj(vararg entries: Pair<String, Any?>): Scriptable = cx.newObject(scope).also { o ->
            entries.forEach { (k, v) -> ScriptableObject.putProperty(o, k, v) }
        }
        fun str(args: Array<Any?>, i: Int) = args.getOrNull(i)?.takeUnless { it is Undefined }?.let { Context.toString(it) }.orEmpty()
        fun int(args: Array<Any?>, i: Int) = args.getOrNull(i)?.let { Context.toNumber(it).toInt() } ?: 0
        fun js(v: Any?) = toJs(cx, scope, v)

        return obj(
            "speak" to fn(scope) { a ->
                val style = (a.getOrNull(1) as? Scriptable)?.get("style", a[1] as Scriptable)?.takeUnless { it == Scriptable.NOT_FOUND }
                api.speak(str(a, 0), style?.let { Context.toString(it) } ?: "calm"); null
            },
            "bell" to fn(scope) { api.bell(); null },
            "notify" to fn(scope) { a -> api.notify(str(a, 0), str(a, 1)); null },
            "vibrate" to fn(scope) { api.vibrate(); null },
            "toast" to fn(scope) { a -> api.toast(str(a, 0)); null },
            "alarm" to obj(
                "set" to fn(scope) { a -> api.alarmSet(int(a, 0), str(a, 1)) },
                "calm" to fn(scope) { a -> api.alarmCalm(int(a, 0), str(a, 1)); null },
            ),
            "time" to obj("now" to fn(scope) { js(api.now()) }),
            "goals" to obj(
                "today" to fn(scope) { js(api.goalsToday()) },
                "checkIn" to fn(scope) { a -> api.checkIn(str(a, 0)) },
            ),
            "http" to obj(
                "get" to fn(scope) { a -> js(api.httpGet(str(a, 0))) },
                "post" to fn(scope) { a ->
                    val body = a.getOrNull(1)
                    val json = if (body is Scriptable) NativeJSON.stringify(cx, scope, body, null, null) as String else str(a, 1)
                    js(api.httpPost(str(a, 0), json))
                },
            ),
            "battery" to fn(scope) { api.battery() },
            "wifi" to fn(scope) { api.wifi() },
            "clipboard" to fn(scope) { a -> api.clipboard(str(a, 0)); null },
            "open" to fn(scope) { a -> api.open(str(a, 0)); null },
            "store" to obj(
                "get" to fn(scope) { a -> js(api.storeGet(str(a, 0))) },
                "set" to fn(scope) { a ->
                    val v = a.getOrNull(1)
                    api.storeSet(str(a, 0), when (v) { null, is Undefined -> null; is Boolean, is String -> v; is Number -> v.toDouble(); else -> Context.toString(v) }); null
                },
            ),
            "run" to fn(scope) { a -> api.run(str(a, 0)) },
        )
    }

    private fun fn(scope: Scriptable, block: (Array<Any?>) -> Any?): BaseFunction = object : BaseFunction(scope, ScriptableObject.getFunctionPrototype(scope)) {
        override fun call(cx: Context, scope: Scriptable, thisObj: Scriptable?, args: Array<Any?>): Any? =
            block(args) ?: Undefined.instance
    }

    private fun toJs(cx: Context, scope: Scriptable, value: Any?): Any? = when (value) {
        null -> null
        is Map<*, *> -> cx.newObject(scope).also { o -> value.forEach { (k, v) -> ScriptableObject.putProperty(o, k.toString(), toJs(cx, scope, v)) } }
        is List<*> -> cx.newArray(scope, value.map { toJs(cx, scope, it) }.toTypedArray())
        is Double -> if (value % 1.0 == 0.0 && value in -1e15..1e15) value.toLong().toInt().takeIf { it.toDouble() == value } ?: value else value
        else -> value
    }

    private fun show(cx: Context, scope: Scriptable, value: Any?): String = when (value) {
        is Scriptable -> if (value is BaseFunction) "[function]" else NativeJSON.stringify(cx, scope, value, null, null) as String
        is Double -> if (value % 1.0 == 0.0) value.toLong().toString() else value.toString()
        else -> Context.toString(value)
    }
}
